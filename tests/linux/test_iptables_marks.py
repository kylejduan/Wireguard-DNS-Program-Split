    def test_other_targets_may_repeat_argument_values(self):
        text = ('*filter\n:INPUT ACCEPT [0:0]\n'
                '-A INPUT -p tcp -j SET --add-set allowed src --del-set pending src\n'
                '-A INPUT -p tcp -j SET --add-set allowed src --exist --timeout 600\n'
                '-A INPUT -j NFLOG --nflog-group 1 --nflog-threshold 1\n'
                '-A INPUT -j LOG --log-prefix --mark --log-level 4\n'  # A value, not an option.
                '-A INPUT -m string --string "--set-mark" --algo bm -j DROP\nCOMMIT\n')
        self.assertEqual(network._legacy_mask(text), 0)
        with self.assertRaises(network.NetworkError):  # Repeats are refused only where marks are written.
            network._legacy_mask('-A OUTPUT -j MARK --set-xmark 0x1/0x1 --set-xmark 0x2/0x2\n')

    def test_quoted_values_may_span_lines_and_hold_escapes(self):
        """libxtables quotes a value with any other character and escapes
        quote, backslash and apostrophe; a comment may hold real newlines."""
        sneaky = 'one line\n-A OUTPUT -j MARK --set-mark 0x1\n"quoted" \\path\\ it\'s mark\n#not a comment'
        text = ('*mangle\n:OUTPUT ACCEPT [0:0]\n-A OUTPUT -m comment --comment' + save_string(sneaky) +
                ' -j ACCEPT\n-A OUTPUT -m comment --comment' + save_string('zone\n--zone 7') +
                ' -m mark --mark 0x10/0x10 -j CT --zone 5\nCOMMIT\n')
        self.assertEqual(network._legacy_mask(text), 0x10)
        self.assertEqual(network._legacy_zones(text), {5})
        self.assertEqual(list(inventory._iptables_records('-A X -m comment --comment' + save_string(sneaky))),
                         [[('-A', False), ('X', False), ('-m', False), ('comment', False), ('--comment', False),
                           (sneaky, True)]])
        for broken in ('-A OUTPUT -m comment --comment "open\n-A OUTPUT -j ACCEPT\n',
                       '-A OUTPUT -m comment --comment "ends in an escape\\'):
            with self.subTest(broken=broken):
                with self.assertRaises(network.NetworkError): network._legacy_mask(broken)
                with self.assertRaises(network.NetworkError): network._legacy_zones(broken)

    def test_fuzzed_comments_and_other_target_arguments_reserve_nothing(self):
        alphabet = ['"', '\\', "'", '\n', ' ', '\t', 'mark', 'MARK', '--set-mark', '--map-mark', '-j', '#',
                    '--zone', 'x', '0x1', ':', '*', 'COMMIT', '-A']
        targets = [['NFLOG', '--nflog-group', '{n}', '--nflog-threshold', '{n}', '--nflog-prefix', '{text}'],
                   ['LOG', '--log-prefix', '{text}', '--log-level', '{n}'],
                   ['SET', '--add-set', 's{n}', 'src', '--del-set', 's{n}', 'src', '--exist'],
                   ['REJECT', '--reject-with', 'icmp-port-unreachable'], ['DNAT', '--to-destination', '10.0.0.{n}:80'],
                   ['NFQUEUE', '--queue-num', '{n}', '--queue-bypass'], ['ACCEPT'], ['RETURN']]
        generator = random.Random(20261015)
        for _ in range(400):
            rules = []
            for _ in range(generator.randrange(1, 6)):
                comment = ''.join(generator.choice(alphabet) for _ in range(generator.randrange(0, 12)))
                target = [part.format(n=generator.randrange(0, 9),
                                      text=''.join(generator.choice(alphabet) for _ in range(generator.randrange(1, 6))))
                          for part in generator.choice(targets)]
                arguments = ''.join(' ' + value if re.fullmatch(r'[-_0-9A-Za-z]+', value) else save_string(value)
                                    for value in target[1:])
                rules.append('-A OUTPUT -m comment --comment' + save_string(comment) + ' -j ' + target[0] + arguments)
            text = '*mangle\n:OUTPUT ACCEPT [0:0]\n' + '\n'.join(rules) + '\nCOMMIT\n'
            if ambiguous(text):
                with self.assertRaises(network.NetworkError, msg=text): network._legacy_mask(text)
                continue
            self.assertEqual(network._legacy_mask(text), 0, text)
            self.assertEqual(network._legacy_zones(text), set(), text)

    def test_quoted_jump_values_cannot_hide_the_real_target(self):
        """Only an unquoted keyword is structural: the target is the rule's one
        unquoted -j or -g, and a second unquoted one is refused."""
        mark = ' -j MARK --set-xmark 0x0/0x3000000'
        for line in ('-A OUTPUT -m string --string "-j" --algo bm --to 65535' + mark,  # The review's case.
                     '-A OUTPUT -m string --string "-g" --algo kmp' + mark,
                     '-A OUTPUT -m string --string "-m" --algo bm' + mark,
                     '-A OUTPUT -m comment --comment' + save_string('-j MARK --set-mark 0x1') + mark,
                     '-A OUTPUT -m comment --comment' + save_string('"-j" ACCEPT') + mark):
            with self.subTest(line=line):
                self.assertEqual(network._legacy_mask(line + '\n'), 0x3000000)
        self.assertEqual(network._legacy_mask('-A OUTPUT -j LOG --log-prefix' + save_string('-j MARK') + '\n'), 0)
        self.assertEqual(network._legacy_mask('-A OUTPUT -m comment --comment' +
                                              save_string('-j MARK --set-mark 0x1') + ' -j ACCEPT\n'), 0)
        # The serializer prints a value of only [-_0-9A-Za-z] bare: "-j" alone is
        # then indistinguishable from a jump, so the rule is refused.
        for line in ('-A OUTPUT -m comment --comment -j' + mark, '-A OUTPUT -m comment --comment -g -j ACCEPT',
                     '-A OUTPUT -m comment --comment --set-mark -j ACCEPT',
                     '-A OUTPUT -m comment --comment --mark -m mark --mark 0x1/0x1 -j ACCEPT'):
            with self.subTest(line=line), self.assertRaises(network.NetworkError):
                network._legacy_mask(line + '\n')
        with self.assertRaises(network.NetworkError):
            network._legacy_zones('-A OUTPUT -m comment --comment -j -j CT --zone 5\n')
        self.assertEqual(network._legacy_zones('-A OUTPUT -m string --string "-j" --algo bm -j CT --zone 5\n'), {5})
        self.assertEqual(network._legacy_zones('-A OUTPUT -j LOG --log-prefix "--zone 9"\n'), set())

    def test_fuzzed_quoted_keywords_never_change_a_real_mark_target(self):
        values = ['-j', '-g', '-m', '--jump', '--goto', '--match', 'MARK', '--set-xmark', '0x1/0x1', 'x', ' ', '\n',
                  '"', '\\', "'", 'mark', '--mark', 'CT', '--zone', '1']
        generator = random.Random(15102026)
        for _ in range(400):
            mask = 1 << generator.randrange(32)
            parts = []
            for _ in range(generator.randrange(1, 4)):
                value = ' '.join(generator.choice(values) for _ in range(generator.randrange(1, 4)))
                parts.append(generator.choice([
                    ' -m string --string "' + value.replace('\\', '\\\\').replace('"', '\\"') + '" --algo bm',
                    ' -m comment --comment' + save_string(value)]))
            line = '-A OUTPUT' + ''.join(parts) + ' -j MARK --set-xmark 0x0/' + hex(mask) + '\n'
            if ambiguous(line):
                with self.assertRaises(network.NetworkError, msg=line): network._legacy_mask(line)
            else:
                self.assertEqual(network._legacy_mask(line), mask, line)

    def test_targets_outside_the_allowlist_are_refused_by_name(self):
        """IPMARK (xtables-addons) replaces the whole packet mark; it, HMARK and
        any target not known to leave the mark alone are refused as conflicts."""
        for line in ('-A OUTPUT -p tcp -j IPMARK --addr dst --and-mask 0xffff --or-mask 0x10000',
                     '-A PREROUTING -j HMARK --hmark-tuple src --hmark-mod 4',
                     '-A OUTPUT -j XTADDONS_FUTURE --whatever 1', '-A OUTPUT -j CLUSTERIP --new',
                     # xtables-addons stateless rewrites; standard xtables has none outside NAT.
                     '-A OUTPUT -j RAWDNAT --to-destination 127.0.0.60/32',
                     # TEE never writes the mark but sends a clone to another gateway.
                     '-A OUTPUT -p udp -j TEE --gateway 192.0.2.9',
                     '-A POSTROUTING -j RAWSNAT --to-source 192.0.2.9/32'):
            name = line.split(' -j ')[1].split()[0]
            with self.subTest(line=line), self.assertRaisesRegex(network.NetworkError, name):
                network._legacy_mask('*mangle\n:OUTPUT ACCEPT [0:0]\n' + line + '\nCOMMIT\n')
        for name in ('IPMARK', 'HMARK', 'XTADDONS_FUTURE'):
            entries = [{'rule': {'expr': [{'xt': {'type': 'target', 'name': name}}]}}]
            self.assertTrue(network._opaque_marks(entries))
            with self.assertRaises(network.NetworkError):  # The dump that would show it is required.
                network._require_mark_visibility(entries, {'iptables-legacy-save': ''})
        self.assertFalse(network._opaque_marks([{'rule': {'expr': [{'xt': {'type': 'target', 'name': 'LOG'}}]}}]))

