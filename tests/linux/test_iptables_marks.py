    def test_chain_names_and_comments_are_not_mark_targets(self):
        text = (':MARK-ME - [0:0]\n:HMARK - [0:0]\n-A OUTPUT -m comment --comment "set mark --set-mark 1" -j MARK-ME\n'
                '-A OUTPUT -j HMARK\n-A OUTPUT -g MARK-ME\n')
        self.assertEqual(network._legacy_mask(text), 0)
        self.assertEqual(network._legacy_mask('-A OUTPUT -m comment --comment "mark" -j ACCEPT\n'), 0)
        # Not declared in this table: an unknown target extension, refused by name.
        with self.assertRaisesRegex(network.NetworkError, 'KUBE-MARK-MASQ'):
            network._legacy_mask('-A OUTPUT -j KUBE-MARK-MASQ\n')
        with self.assertRaises(network.NetworkError):
            network._legacy_mask(':KUBE-MARK-MASQ - [0:0]\n-A OUTPUT -j KUBE-MARK-MASQ --or-mark 0x1\n')

    def test_ipset_and_socket_mark_writes_are_refused(self):
        """SET --map-mark writes marks held in mutable ipset entries and socket
        --restore-skmark copies a socket's mark: neither can be bounded."""
        for line in ('-A OUTPUT -m mark --mark 0x0/0xff -j SET --map-set route_marks dst --map-mark',
                     '-A OUTPUT -j SET --map-set route_marks dst --map-mark --map-prio',
                     '-A PREROUTING -p tcp -m socket --transparent --restore-skmark -j ACCEPT'):
            with self.subTest(line=line), self.assertRaises(network.NetworkError):
                network._legacy_mask(line + '\n')
        self.assertEqual(network._legacy_mask('-A OUTPUT -j SET --add-set seen src\n'
                                              '-A OUTPUT -m set --match-set seen src -j ACCEPT\n'), 0)
        for name in ('SET', 'socket'):
            self.assertTrue(network._opaque_marks([{'rule': {'expr': [{'xt': {'type': 'target', 'name': name}}]}}]))

    def test_nft_kube_proxy_constant_bit_operations_reserve_their_bits(self):
        mark = {'meta': {'key': 'mark'}}
        def write(value): return {'mangle': {'key': mark, 'value': value}}
        rules = [{'rule': {'family': 'ip', 'table': 'kube-proxy', 'chain': 'mark-for-masquerade',
                           'expr': [write({'|': [mark, 0x4000]})]}},
                 {'rule': {'family': 'ip', 'table': 'kube-proxy', 'chain': 'masquerading', 'expr': [
                     {'match': {'op': '==', 'left': {'&': [mark, 0x4000]}, 'right': 0}}, {'return': None}]}},
                 {'rule': {'family': 'ip', 'table': 'kube-proxy', 'chain': 'masquerading',
                           'expr': [write({'^': [mark, 0x4000]}), {'masquerade': {'flags': 'fully-random'}}]}}]
        self.assertEqual(network._nft_usage(rules)[0], 0x4000)
        for value, bits in (({'&': [mark, 0xffffbfff]}, 0x4000), ({'^': [{'&': [mark, 0xff00ffff]}, 0x10000]}, 0xff0000),
                            ({'|': [{'&': [mark, 0xffffffff]}, 0x1]}, 0x1)):
            with self.subTest(value=value):
                self.assertEqual(network._nft_usage([{'rule': {'expr': [write(value)]}}])[0], bits)
        with self.assertRaises(network.NetworkError):
            network._nft_usage([{'rule': {'expr': [write({'&': [{'&': [mark, 0xff]}, 0x1]})]}}])

