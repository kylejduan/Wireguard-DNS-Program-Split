class QuotedJumpInventoryTests(unittest.TestCase):
    """The review's rule in a real inventory: allocation avoids its bits and a
    running network's health reports it, in legacy and iptables-nft dumps."""
    CASE = '-A OUTPUT -m string --string "-j" --algo bm --to 65535 -j MARK --set-xmark 0x0/{mask}\n'

    def setUp(self):
        stack = ExitStack(); self.addCleanup(stack.close)
        stack.enter_context(patch('wg_program_split.inventory.shutil.which', lambda tool, path=None: '/usr/sbin/' + tool))

    def test_allocation_avoids_the_bits_behind_a_quoted_jump(self):
        for flavour in ('legacy', 'nft_save'):
            with self.subTest(flavour=flavour):
                kernel = Kernel()
                setattr(kernel, flavour, '*mangle\n' + self.CASE.format(mask='0x3000000') + 'COMMIT\n')
                allocation = network.allocate(network.inspect(PROFILE, runner=kernel))
                self.assertFalse(allocation.mask & 0x3000000, hex(allocation.mask))

    def test_ipmark_is_refused_in_allocation_from_either_dump_and_nft_compat_form(self):
        rule = '*mangle\n-A OUTPUT -p tcp -j IPMARK --addr dst --and-mask 0xffff --or-mask 0x10000\nCOMMIT\n'
        for flavour in ('legacy', 'nft_save'):
            with self.subTest(flavour=flavour):
                kernel = Kernel()
                setattr(kernel, flavour, rule)
                if flavour == 'nft_save':  # iptables-nft: nft -j shows only an opaque xt target.
                    kernel.nft['nftables'].append({'rule': {'family': 'ip', 'table': 'mangle', 'chain': 'OUTPUT',
                                                            'expr': [{'xt': {'type': 'target', 'name': 'IPMARK'}}]}})
                with self.assertRaisesRegex(network.NetworkError, 'IPMARK'):
                    network.inspect(PROFILE, runner=kernel)

    def test_health_reports_a_quoted_jump_rule_over_the_owned_mask(self):
        with tempfile.TemporaryDirectory(dir=Path.home()) as root:
            state, wireguard = Path(root) / 'state', Path(root) / 'wireguard'
            state.mkdir(mode=0o700); wireguard.mkdir(mode=0o700)
            fd = ownership.open_private_dir(state, owner_uid=os.getuid())
            try:
                kernel = Kernel()
                net = network.Network(PROFILE, fd, runner=kernel, boot_id=BOOT, wireguard_root=wireguard,
                                      owner_uid=os.getuid())
                net.prepare(guard_blocked=True)
                self.assertTrue(net.health().ready)
                for flavour in ('legacy', 'nft_save'):
                    setattr(kernel, flavour, '*mangle\n' + self.CASE.format(mask=hex(net.allocation.mask)) + 'COMMIT\n')
                    self.assertIn('allocation:foreign', net.health().changed)
                    setattr(kernel, flavour, '')
                    self.assertTrue(net.health().ready)
            finally:
                os.close(fd)


